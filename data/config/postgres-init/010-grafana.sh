#!/bin/sh

set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${GRAFANA_DB_USER}') THEN
    CREATE ROLE "${GRAFANA_DB_USER}" WITH LOGIN PASSWORD '${GRAFANA_DB_PASSWORD}';
  ELSE
    ALTER ROLE "${GRAFANA_DB_USER}" WITH LOGIN PASSWORD '${GRAFANA_DB_PASSWORD}';
  END IF;
END
\$\$;

SELECT 'CREATE DATABASE "${GRAFANA_DB_NAME}" OWNER "${GRAFANA_DB_USER}"'
WHERE NOT EXISTS (
  SELECT 1 FROM pg_database WHERE datname = '${GRAFANA_DB_NAME}'
)\gexec
SQL